def auto_minimums(key, std, label_prefix, names_):
    out = []
    mins = {k: dict(v) for k, v in MINS[key].items()}
    for c, v in EXTRA[key].items():
        mins.setdefault(c, {}).update(v)
    for c in sorted(mins, key=lambda s: [float(x) for x in s.split(".")]):
        m = mins[c]
        nm = names_.get(c, {})
        for what in ("width", "area", "length"):
            if what not in m:
                continue
            u = "mm²" if what == "area" else "mm"
            word = {"width": ("minimum width", "largeur minimale"), "area": ("minimum area", "surface minimale"),
                    "length": ("minimum length", "longueur minimale")}[what]
            e = E(f"{label_prefix}.min.{c}.{what}", f"{std} {c}", [c], "check", what, "error",
                  f"{c} {nm.get('en', '')}: {word[0]} {m[what]:g} {u}.",
                  f"{c} {nm.get('fr', '')} : {word[1]} {str(m[what]).replace('.', ',')} {u}.",
                  "Exaggerated or given to a neighbour where safe (an area), else reported.")
            e["value"] = m[what]                               # map mm (mm² for an area) at the standard's own scale
            out.append(e)
    return out


def build():
    sp_names, fo_names = names("ms.sp.s."), names("ms.s.")
    for fname, std, rules, key, pfx, nm in (
            ("rules-issprom2019-2.json", "ISSprOM 2019-2", SPRINT, "issprom", "sp", sp_names),
            ("rules-isom2017-2.json", "ISOM 2017-2", FOREST, "isom", "fo", fo_names)):
        allr = rules + auto_minimums(key, std, pfx, nm)
        ids = [r["id"] for r in allr]
        assert len(ids) == len(set(ids)), [i for i in ids if ids.count(i) > 1]
        doc = {"format": "ozimut-rules", "version": 1, "standard": std,
               "about": "Every rule of the specification filed as generator / check / manual (docs/mapper/standards.py).",
               "counts": {k: sum(1 for r in allr if r["kind"] == k) for k in ("generator", "check", "manual")},
               "rules": allr}
        lines = ['{"format":"ozimut-rules","version":1,"standard":' + json.dumps(std) + ',',
                 '"about":' + json.dumps(doc["about"]) + ',', '"counts":' + json.dumps(doc["counts"]) + ',', '"rules":[',
                 ",\n".join(json.dumps(r, ensure_ascii=False) for r in allr), "]}"]
        (SETS / fname).write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
        print(fname, len(allr), doc["counts"])


if __name__ == "__main__":
    build()
