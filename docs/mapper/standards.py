"""The rule catalogues of the two map specifications, every general rule and every symbol, each filed as one of three kinds:

  generator — what the town map generator (tools/virtually/town_map.py, mkocd.mjs) or the symbol sets (docs/mapper/sets.mjs) do;
  check     — measured on a map by tools/virtually/legibility.py and, where marked, Cartographier's checks (mapper/checks.js);
  manual    — for the mapper to see to on the map (no measurable criterion, or one the generated data cannot carry).

  py docs/mapper/standards.py   ->  site/assets/js/mapper/sets/rules-issprom2019-2.json, rules-isom2017-2.json

Sources: ISSprOM 2019-2 (IOF, its English text with FFCO's French translation) and revision 6 (January 2024, the Czech federation's
translation, the only copy of that revision found); ISOM 2017-2 (FFCO's FR/EN edition of June 2019) and its revision 6 errata. The
paragraph cited is the specification's (§2.2, §3.3…) or the symbol's number. The sizes per symbol come from minimums.json (written
by sets.mjs from the same texts) with revision 6's changes on top (`EXTRA`); each becomes an automatic entry of its own.

Each entry: id, ref, sym (symbol numbers), kind, check (the check's key, or null), sev (error = « shall / must », the map is not
published with it left unlisted; warn = « should »; info), status (« implemented » or « planned » for a check not written yet),
en, fr (the rule in a sentence), how (what the generator or the check does). Keep the ids stable: the review sheets and the
regression tests name them."""
