def names(prefix):
    out = {}
    for lang in ("fr", "en"):
        txt = open(I18N / f"{lang}.js", encoding="utf-8").read()
        for k, v in re.findall(r'"' + re.escape(prefix) + r'([0-9.]+)":\s*"((?:[^"\\]|\\.)*)"', txt):
            out.setdefault(k, {})[lang] = v.replace('\\"', '"')
    return out


def E(id, ref, sym, kind, check, sev, en, fr, how="", status="implemented"):
    return {"id": id, "ref": ref, "sym": sym if isinstance(sym, list) else ([sym] if sym else []), "kind": kind,
            "check": check, "sev": sev, "status": status if check else None, "en": en, "fr": fr, "how": how}


